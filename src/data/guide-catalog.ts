/** 按价位段取名录：给出「预算多少，这个区间里有什么」 */
export function guideInBudget(max: number): GuideEntry[] {
  return guideCatalog.filter((g) => g.priceMin <= max);
}

/** 按定位筛选 */
export function guideByCategory(category: GuideCategory): GuideEntry[] {
  return guideCatalog.filter((g) => g.category === category);
}

/** 价位段转成人话：4500-5500 -> 4500~5500 元；20000-null -> 20000 元以上 */
export function formatPriceBand(g: GuideEntry): string {
  return g.priceMax === null ? `${g.priceMin} 元以上` : `${g.priceMin}~${g.priceMax} 元`;
}

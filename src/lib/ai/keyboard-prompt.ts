export const KEYBOARD_FIELD_GUIDE = `
- budgetMin / budgetMax：预算下限 / 上限，单位「元」。用户说"800以内""预算800"→ budgetMax 800；"300到500"→ budgetMin 300, budgetMax 500。
- layouts：配列，数组，取值只能是 60 / 65 / 75 / 80 / 98 / 100（对应 60% / 65% / 75% / 80%TKL / 98% / 100%全尺寸）。用户说"小键盘""迷你"→ ["60"]；"带方向键"→ ["65"]；"75配列""带旋钮"→ ["75"]；"TKL""不要数字区"→ ["80"]；"带数字区""小数字键盘"→ ["98"]；"全尺寸""全键"→ ["100"]。
- switchTypes：轴体类型，数组，取值只能是 linear / tactile / clicky / magnetic / optical / low-profile（对应 线性轴 / 段落轴 / 青轴 / 磁轴 / 光轴 / 矮轴）。用户说"红轴""直上直下"→ ["linear"]；"茶轴""有段落感"→ ["tactile"]；"青轴""咔哒"→ ["clicky"]；"磁轴""RT""快速触发""打FPS"→ ["magnetic"]；"光轴"→ ["optical"]；"矮轴""薄"→ ["low-profile"]。
- connections：连接方式，数组，取值只能是 wired / wireless24g / bluetooth（对应 有线 / 2.4G无线 / 蓝牙）。注意：用户说"三模"→ ["wired","wireless24g","bluetooth"]（三种都要）；"蓝牙""多设备切换"→ ["bluetooth"]；"2.4G""接收器"→ ["wireless24g"]；"有线"→ ["wired"]。
- webDriver：是否提供网页驱动（打开浏览器就能调键位/灯效，无需装桌面客户端），布尔值。用户说"网页驱动""浏览器驱动""不用装驱动"→ true。没提就省略。
- usages：用途，数组，取值只能是 gaming / office / general（对应 游戏 / 办公 / 通用）。用户说"打游戏""电竞""FPS"→ ["gaming"]；"办公""打字""写文档"→ ["office"]；"什么都干""日用"→ ["general"]。
`;

